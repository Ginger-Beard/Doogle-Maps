/**
 * Every patch's real position and footprint, measured from a live client.
 *
 * <h2>Measured, not hand-authored — which is the whole point</h2>
 *
 * {@link PatchLocationStore}'s class note explains why positions were learned rather than listed:
 * RuneLite's farming data identifies a patch by region and varbit and never needs to walk
 * anywhere, so there is no coordinate table to mirror, and <i>"hand-authoring 107 of them would
 * be a lot of data to get subtly wrong and then maintain"</i>.
 *
 * <p>That was a good reason while nothing could measure them. The plugin measures them now. Every
 * entry below was read off the client by standing next to the patch and watching its game objects
 * spawn — the same {@code PatchLocationCapture} path that fills the per-profile store — and then
 * dumped out of a profile that had visited all 107. Nobody typed a coordinate.
 *
 * <h2>Why it is worth having at all, when the store already learns them</h2>
 *
 * Because the store learns them <b>per RuneScape profile</b>, so every account starts blind and
 * relearns the same immutable facts. A patch's position is a fact about the game world, not about
 * an account. Baked in, every account has all of it from first launch; the learned store keeps
 * working on top as a self-correcting refinement, and wins wherever it has something.
 *
 * <p>What that buys, concretely: within a stop, patches are ordered nearest-first, and that needs
 * each to have its own coordinate. {@code WikiPatchLocations} publishes one pin per <i>location</i>
 * — the wiki's own granularity — so every patch in a region returned the identical point, compared
 * equal, and the order collapsed to declaration order. The Hosidius vinery is the extreme: twelve
 * grape patches on one pin, now twelve positions one to thirteen tiles apart.
 *
 * <h2>The shape, and the hespori</h2>
 *
 * {@code {x, y, plane, sizeX, sizeY, swX, swY}} — the same seven the learned store uses. The point
 * is a tile the patch <b>occupies</b> and the corner plus size is its extent; the two are separate
 * because patches are frequently not rectangles. See {@code PatchLocationStore.record}.
 *
 * <p>The hespori is included and is <b>known to be wrong</b>. Its patch is in an instanced cave, so
 * the coordinate read there is instance-space and means nothing on the world map. It is harmless
 * because it is never served: {@code PatchLocationStore.getLocation} answers the hespori with the
 * cave's overworld <i>entrance</i> before consulting any tier, and {@code record} refuses to learn
 * it, for the same reason this row cannot be trusted. The row stays so the table is the complete
 * measured set rather than the set minus one unexplained gap — and so a regeneration, which walks
 * every patch and dumps what it saw, does not look like it lost one.
 *
 * <h2>Regenerating</h2>
 *
 * Visit every patch with the plugin running, then dump the profile's {@code patchLocations} blob.
 * It is not generated by a script in {@code tools/} because it is not derived from anything —
 * it is an observation, and the observation costs about two and a half hours of walking.
 */
