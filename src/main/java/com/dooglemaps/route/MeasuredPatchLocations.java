	private MeasuredPatchLocations()
	{
	}

	/**
	 * This patch's measured position and extent, or null when it was never observed.
	 *
	 * <p>The array is copied on the way out. It is handed to callers that read it positionally and
	 * a shared mutable one is a table that can be edited by accident.
	 */
	@Nullable
	public static int[] forPatch(FarmPatch patch)
	{
		int[] measured = MEASURED.get(patch.getKey());
		return measured == null ? null : measured.clone();
	}

	/** How many patches the table covers, for the tests that pin it against the world data. */
	public static int size()
	{
		return MEASURED.size();
	}
